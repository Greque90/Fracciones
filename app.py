def ai_interpret(image_bytes, mime_type, consigna, contexto):
    """Asistencia opcional. Requiere OPENAI_API_KEY y paquete openai."""
    try:
        from openai import OpenAI
    except ImportError:
        raise RuntimeError("Falta instalar el paquete openai. Ejecutá: pip install openai")
    api_key = st.secrets.get("OPENAI_API_KEY", os.getenv("OPENAI_API_KEY", ""))
    if not api_key:
        raise RuntimeError("No se encontró OPENAI_API_KEY. Configurala en .streamlit/secrets.toml o como variable de entorno.")
    client = OpenAI(api_key=api_key)
    data_url = f"data:{mime_type};base64,{base64.b64encode(image_bytes).decode('utf-8')}"
    prompt = f"""
Actuá como asistente de análisis didáctico para formación docente en Matemática.
Analizá la imagen de una producción estudiantil. Consigna: {consigna}
Contexto didáctico: {contexto}

Respondé en español y en JSON válido con estas claves:
- transcripcion: texto matemático/verbal visible. Si no se lee, indicá [ilegible] o [parcial].
- observaciones: lista de hechos observables (sin inferencias).
- estrategia_posible: hipótesis prudente sobre el procedimiento.
- categorias: lista de códigos posibles elegidos solo entre:
{json.dumps(list(CATEGORIAS.keys()), ensure_ascii=False)}
- preguntas_docentes: lista de preguntas que permitirían validar la hipótesis.
- cautelas: lista de aspectos que no pueden concluirse solo con esta imagen.

No asignes notas, no diagnostiques al estudiante, no supongas identidad ni edad.
Diferenciá explícitamente lo observado de lo inferido. Si hay ambigüedad, declarala.
"""
    response = client.chat.completions.create(
        model=os.getenv("OPENAI_MODEL", "gpt-4o-mini"),
        temperature=0.2,
        response_format={"type": "json_object"},
        messages=[{
            "role": "user",
            "content": [
                {"type": "text", "text": prompt},
                {"type": "image_url", "image_url": {"url": data_url}}
            ]
        }]
    )
    return json.loads(response.choices[0].message.content)

def export_excel(rows):
    output = BytesIO()
    with pd.ExcelWriter(output, engine="openpyxl") as writer:
        df = pd.DataFrame(rows)
        if df.empty:
            df = pd.DataFrame(columns=["codigo", "transcripcion", "observaciones", "estrategia", "categorias", "patrones", "preguntas", "validacion", "cautelas"])
        df.to_excel(writer, index=False, sheet_name="Evidencias")
        resumen = []
        for cat in CATEGORIAS:
            count = sum(cat in (r.get("categorias") or []) for r in rows)
            resumen.append({"Categoria": cat, "Descripcion": CATEGORIAS[cat], "Frecuencia": count})
        pd.DataFrame(resumen).to_excel(writer, index=False, sheet_name="Categorias")
        if rows:
            pd.DataFrame([{"Patrón": p, "Frecuencia": sum(p in (r.get("patrones") or []) for r in rows)} for p in PATRONES]).to_excel(writer, index=False, sheet_name="Regularidades")
    output.seek(0)
    return output.getvalue()

